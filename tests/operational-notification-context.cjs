const assert = require('node:assert/strict');
const { loader } = require('./support/load-ts.cjs');
const load = loader();
const { operationalNotificationTiming: timing, shouldNotifyIncidentTimeout: timeout } = load('src/services/operationalNotificationTiming.ts');
const { operationalNotificationText: text } = load('src/services/operationalNotificationText.ts');
const now = Date.parse('2026-10-15T12:00:00Z');
assert.equal(timing(new Date(now-299999), now).notify, true);
assert.equal(timing(new Date(now-300000), now).notify, false);
assert.equal(timing('invalid', now).notify, false);
assert.equal(timing(new Date(now+120000), now).notify, false);
assert.equal(timing(undefined, now).notify, true, 'Legacy timestamp-free jobs remain compatible');
assert.equal(timeout({ estado:'CERRADO', fechaFin:new Date(now-1000) }, now), true);
for (const record of [null, {estado:'ABIERTO',fechaFin:new Date(now)}, {estado:'RESUELTO',fechaFin:new Date(now)}, {estado:'CERRADO'}, {estado:'CERRADO',fechaFin:new Date(now-300001)}]) assert.equal(timeout(record, now), false);
const data = { movimientoId:41, incidenteId:7, localidadId:2, locomotora:'1234' };
const first = text({ title:'Incidente resuelto', body:'ID #7 · Loco 1234' }, data);
assert.equal(first.title, 'Incidente resuelto');
for (const value of ['Incidente #7','Movimiento #41','Locomotora 1234','Patio 2']) assert.equal(first.body.split(value).length-1, 1);
assert.equal(text(first, data).body, first.body, 'Formatting twice never duplicates identifiers');
const arrastre = text({ title:'Arrastre detenido', body:'Arrastre #4 detenido por incidente #3' }, { arrastreId:4, incidenteId:3, localidadId:2 });
assert.ok(arrastre.body.includes('detenido por incidente #3')); assert.equal(arrastre.body.match(/Arrastre #4/g).length,1);
const long = text({ title:'Incidente reportado', body:'detalle '.repeat(100) }, data);
assert.ok(long.body.length <= 240); for (const value of ['Movimiento #41','Incidente #7','Patio 2']) assert.ok(long.body.includes(value));
const lateIdentity = text({ title:'Movimiento actualizado', body:'Detalle largo '.repeat(25)+'Movimiento #42' }, {movimientoId:42,localidadId:2});
assert.ok(lateIdentity.body.length<=240); assert.ok(lateIdentity.body.includes('Movimiento #42'));
const custom = text({ title:'Mensaje personalizado', body:'Revisar acceso' }, {}); assert.equal(custom.body,'Revisar acceso');
const patio = load('src/services/patioNotificationPolicy.ts').patioStartNotice({ movimientoId:41, localidadId:2, locomotiveNumber:1234, descripcion:'PRIVATE', empresa:'PRIVATE', snapshot:{private:true} });
assert.match(patio.notificationBody,/Patio 2/); assert.equal(JSON.stringify(patio).includes('PRIVATE'),false);
console.log('PASS operational alerts: server event expiry, incident state, bounded text, exact identity and public patio privacy');
